function ellipseEyes(cx, y, gap, r) {
  return `<ellipse cx="${cx - gap}" cy="${y}" rx="${r}" ry="${r * 1.35}" fill="${'#293040'}" stroke="none"/>` +
    `<circle cx="${cx - gap + 6}" cy="${y - 6}" r="4" fill="#fff" stroke="none"/>` +
    `<ellipse cx="${cx + gap}" cy="${y}" rx="${r}" ry="${r * 1.35}" fill="#293040" stroke="none"/>` +
    `<circle cx="${cx + gap + 6}" cy="${y - 6}" r="4" fill="#fff" stroke="none"/>`;
}

