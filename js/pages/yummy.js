const makeBunting = (tones = [1, 3, 2, 4, 3, 1, 2]) => {
  const start = { x: 205, y: 64 };
  const control = { x: 500, y: 120 };
  const end = { x: 795, y: 68 };
  const tValues = [0.12, 0.25, 0.38, 0.5, 0.62, 0.75, 0.88];
  const points = tValues.map((t) => {
    const u = 1 - t;
    return {
      x: u * u * start.x + 2 * u * t * control.x + t * t * end.x,
      y: u * u * start.y + 2 * u * t * control.y + t * t * end.y,
    };
  });
  const regions = points
    .map(({ x, y }, i) => P(`${x - 33} ${y} ${x + 33} ${y + 3} ${x} ${y + 48}`, tones[i]))
    .join('');
  const details =
    L(`M ${start.x} ${start.y} Q ${control.x} ${control.y} ${end.x} ${end.y}`, 'stroke-width="5"') +
    L(`M ${start.x} ${start.y} Q 188 84 176 108 M ${end.x} ${end.y} Q 812 88 824 112`, 'stroke-width="5"');
  return { regions, details };
};

